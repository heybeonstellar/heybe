// Renders EVIDENCE.md from deployments/testnet.json and deployments/evidence/*.json.
//
//   cd scripts && npm run evidence

import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { ROOT, contractLink, deployments as d } from "./lib/heybe.ts";

type Step = { step: string; claim: string; hash?: string; explorer?: string; result?: string };
type Flow = { flow: string; recordedAt: string; context: Record<string, unknown>; steps: Step[] };

const TITLES: Record<string, string> = {
  core: "Core flow: control follows the NFT",
  "stellar-8004": "stellar-8004 flow: an agent NFT with its own wallet",
};
const ORDER = ["core", "stellar-8004"];

const dir = join(ROOT, "deployments", "evidence");
const flows: Flow[] = readdirSync(dir)
  .filter((f) => f.endsWith(".json"))
  .map((f) => JSON.parse(readFileSync(join(dir, f), "utf8")))
  .sort((a, b) => ORDER.indexOf(a.flow) - ORDER.indexOf(b.flow));

const short = (s: string) => (s.length > 20 ? `${s.slice(0, 6)}…${s.slice(-6)}` : s);
const link = (label: string, url: string) => `[${label}](${url})`;
const cell = (s: string) => s.replace(/\|/g, "\\|");

const out: string[] = [];
out.push("# Evidence");
out.push("");
out.push(
  "Every claim below links to a public Stellar **testnet** transaction or to a read of on-chain state. " +
    "The flows are scripted (`scripts/flows/`), so anyone can re-run them and get a fresh set of hashes. " +
    "This file is generated by `scripts/evidence.ts`.",
);
out.push("");
out.push("## Deployment");
out.push("");
out.push("| Contract | Address |");
out.push("|---|---|");
out.push(`| Heybe registry | ${link(d.registry, contractLink(d.registry))} |`);
out.push(`| Heybe account wasm hash | \`${d.accountWasmHash}\` |`);
out.push(`| Heybe test NFT (OpenZeppelin SEP-50) | ${link(d.testNft, contractLink(d.testNft))} |`);
out.push(`| XLM (Stellar Asset Contract) | ${link(d.xlmSac, contractLink(d.xlmSac))} |`);
out.push(`| stellar-8004 identity registry (third party, unchanged) | ${link(d.stellar8004IdentityRegistry, contractLink(d.stellar8004IdentityRegistry))} |`);
out.push("");

for (const f of flows) {
  out.push(`## ${TITLES[f.flow] ?? f.flow}`);
  out.push("");
  out.push(`Recorded ${f.recordedAt.slice(0, 16).replace("T", " ")} UTC with \`npm run ${f.flow === "core" ? "flows" : "flow:8004"}\`.`);
  out.push("");
  const ctx = f.context;
  const facts: string[] = [];
  if (ctx.account) facts.push(`Heybe account: ${link(String(ctx.account), contractLink(String(ctx.account)))}`);
  if (ctx.tokenId !== undefined) facts.push(`bound to test NFT #${ctx.tokenId}`);
  if (ctx.agentId !== undefined) facts.push(`bound to stellar-8004 agent #${ctx.agentId}`);
  if (ctx.ali) facts.push(`Ali \`${short(String(ctx.ali))}\`, Ayşe \`${short(String(ctx.ayse))}\`, Bob \`${short(String(ctx.bob))}\``);
  if (facts.length) {
    out.push(facts.join(" · "));
    out.push("");
  }
  out.push("| # | Step | Claim | Proof |");
  out.push("|---|---|---|---|");
  f.steps.forEach((s, i) => {
    const proof = [s.hash ? link(`tx ${s.hash.slice(0, 8)}`, s.explorer!) : "", s.result ? `\`${cell(s.result)}\`` : ""]
      .filter(Boolean)
      .join(" → ");
    out.push(`| ${i + 1} | \`${s.step}\` | ${cell(s.claim)} | ${proof} |`);
  });
  out.push("");
}

out.push("## Contract tests");
out.push("");
out.push("26 tests run in CI (`.github/workflows/ci.yml`) and locally:");
out.push("");
out.push("```bash");
out.push("cd contracts && stellar contract build && cargo test");
out.push("```");
out.push("");
out.push("- `heybe-account` (19): Path A payments, control moving with the NFT, strangers and previous owners rejected, other NFTs held and sent, self-transfer and self-ownership guards, burned NFT, lock rules, and Path B with real CAP-71 auth entries (`set_auths`): owner delegate accepted, non-owner, extra and missing delegates rejected, delegation follows the NFT, lock respected.");
out.push("- `heybe-registry` (7): deterministic addresses, permissionless single creation, `created` event, funds sent before deployment, end-to-end flow and Path B against the compiled account wasm.");
out.push("");
out.push("## Not yet covered");
out.push("");
out.push("- Freighter signing a CAP-71 delegate entry in the browser. Path B is proven with a G key in scripts; the wallet path is tested with the web demo.");
out.push("- Passkey (`C...`) owners on testnet. Tests cover contract owners, which use the same host path.");
out.push("");

writeFileSync(join(ROOT, "EVIDENCE.md"), out.join("\n"));
console.log("Wrote EVIDENCE.md");
